"""Render the main and complete Test tables from the archived metric summary."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
TASKS = [
    ('speed', 'Speed', ['Speed']),
    ('action_strength', 'Pusher displacement', ['Pusher', 'displacement']),
    ('robot_arm_mass', 'Arm mass', ['Arm mass']),
    ('action_delay', 'Action delay', ['Action delay']),
    ('contact_friction', 'Contact friction', ['Contact', 'friction']),
    ('motion_damping', 'Motion damping', ['Motion', 'damping']),
    ('cube_gripper_carry', 'Gripper carry rule', ['Gripper', 'carry rule']),
    ('door', 'Door traversability', ['Door', 'traversability']),
    ('portal_exit', 'Portal exit', ['Portal exit']),
]
FAMILIES = [('lewm', 'LeWM'), ('pldm', 'PLDM'), ('dinowm', 'DINO-WM')]
SCHEMES = {'original': 'Original', 'scratch': 'Mixed',
           'joint': r'Original $\to$ Mixed (Joint)',
           'frozen': r'Original $\to$ Mixed (Frozen Encoder)'}
COLUMNS = [(f, r) for f, _ in FAMILIES for r in SCHEMES
           if not (f == 'dinowm' and r == 'joint')]
METRICS = [('accuracy', r'Acc. $\uparrow$', 2),
           ('history', r'History $\uparrow$', 2),
           ('nre', r'NRE $\downarrow$', 3)]


def scheme_label(family, regime):
    if family == 'dinowm' and regime == 'frozen':
        return r'Original $\to$ Mixed'
    return SCHEMES[regime].replace('Mixed (Frozen', r'Mixed\newline (Frozen')


def main_table(index):
    lines = [r'''% Generated by paper/generate_test_tables.py; do not edit values.
\begin{table*}[t]
\centering
\scriptsize
\setlength{\tabcolsep}{2.2pt}
\renewcommand{\arraystretch}{1.03}
\caption{\textbf{Adaptation metrics on the Test split.} Accuracy and History are percentages (higher is better); NRE is normalized response error (lower is better). Joint and Frozen denote the two Original $\to$ Mixed schemes. Speed uses the same scoring rule for Accuracy and History. Entries are means; run counts and standard deviations appear in Table~\ref{tab:test-metrics-full}. Bold marks the highest displayed Accuracy or History per task. NRE is measured in each checkpoint's target representation. A dash denotes no comparable checkpoint.}
\label{tab:test-results}
\begin{tabularx}{\textwidth}{@{}p{1.7cm}l*{11}{>{\centering\arraybackslash}X}@{}}
\toprule
& & \multicolumn{4}{c}{LeWM} & \multicolumn{4}{c}{PLDM} & \multicolumn{3}{c}{DINO-WM} \\
\cmidrule(lr){3-6}\cmidrule(lr){7-10}\cmidrule(lr){11-13}
Task & Metric & Original & Mixed & Joint & Frozen & Original & Mixed & Joint & Frozen & Original & Mixed & \shortstack{Original\\$\to$ Mixed} \\
\midrule''']
    for task, _, task_lines in TASKS:
        for i, (metric, label, decimals) in enumerate(METRICS):
            values = [index.get((task, f, r), {}).get('scores', {}).get(metric, {}).get('mean')
                      for f, r in COLUMNS]
            best = max(round(v, decimals) for v in values if v is not None)
            cells = []
            for value in values:
                if value is None:
                    cells.append('---')
                    continue
                text = f'{value:.{decimals}f}'
                if metric != 'nre' and round(value, decimals) == best:
                    text = r'\textbf{' + text + '}'
                cells.append(text)
            lines.append(' & '.join([task_lines[i] if i < len(task_lines) else '', label, *cells]) + r' \\')
        lines.append(r'\addlinespace[3pt]')
    lines[-1] = r'\bottomrule'
    lines.append(r'\end{tabularx}\end{table*}')
    return '\n'.join(lines) + '\n'


def full_table(index):
    lines = [r'''% Generated by paper/generate_test_tables.py; do not edit values.
\begingroup
\small
\setlength{\tabcolsep}{3pt}
\renewcommand{\arraystretch}{1.08}
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{2.55cm}l>{\raggedright\arraybackslash}p{4.05cm}rrrr@{}}
\caption{\textbf{Complete Test adaptation metrics.} Each row uses the same evaluated checkpoints for all three metrics. Entries are means $\pm$ sample standard deviations across $n$ training runs; a single run has no sample standard deviation. Accuracy and History are percentages; NRE is dimensionless. Speed uses unseen interpolation speeds, and its Accuracy and History use the same scoring rule. Action delay uses seven-frame history. Only available comparable configurations are listed.}\label{tab:test-metrics-full}\label{tab:test-variability}\\
\toprule
Task & Model & Training scheme & $n$ & Accuracy $\uparrow$ & History $\uparrow$ & NRE $\downarrow$ \\
\midrule\endfirsthead
\toprule
Task & Model & Training scheme & $n$ & Accuracy $\uparrow$ & History $\uparrow$ & NRE $\downarrow$ \\
\midrule\endhead
\bottomrule\endfoot''']
    for task, name, _ in TASKS:
        for family, model in FAMILIES:
            for regime in SCHEMES:
                cell = index.get((task, family, regime))
                if cell is None:
                    continue
                values = []
                for metric, _, decimals in METRICS:
                    stat = cell['scores'][metric]
                    value = f"{stat['mean']:.{decimals}f}"
                    if stat['std'] is not None:
                        value = '$' + value + r'\pm' + f"{stat['std']:.{decimals}f}" + '$'
                    values.append(value)
                lines.append(' & '.join([name, model, scheme_label(family, regime), str(cell['n']), *values]) + r' \\')
        lines.append(r'\addlinespace[3pt]')
    lines.append(r'\end{longtable}\endgroup')
    return '\n'.join(lines) + '\n'


def write_tables():
    data = json.loads((ROOT / 'docs/research/data/current_reference_test_v1/metrics.json').read_text())
    assert data['evaluation_split'] == 'test'
    index = {(c['task'], c['family'], c['regime']): c for c in data['cells']}
    assert len(index) == len(data['cells']) == 86
    assert sum(c['n'] for c in index.values()) == 136
    for cell in index.values():
        assert all(cell['scores'][k]['n'] == cell['n'] for k, _, _ in METRICS)
    out = ROOT / 'paper/tables'
    out.mkdir(exist_ok=True)
    (out / 'test_metrics_main.tex').write_text(main_table(index))
    (out / 'test_metrics_full.tex').write_text(full_table(index))
    print('Rendered 86 Test configurations with three metrics in main and appendix tables.')


if __name__ == '__main__':
    write_tables()
