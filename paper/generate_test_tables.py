"""Render the main and complete Test tables from the archived metric summary."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
TASKS = [
    ('speed', 'Speed', ['Speed']),
    ('action_strength', 'Pusher displacement', ['Pusher', 'displacement']),
    ('robot_arm_mass', 'Arm mass', ['Arm mass']),
    ('action_delay', 'Action delay', ['Action delay']),
    ('contact_friction', 'Contact friction', ['Contact', 'friction']),
    ('motion_damping', 'Motion damping', ['Motion', 'damping']),
    ('cube_gripper_carry', 'Gripper carry rule', ['Gripper', 'carry rule']),
    ('door', 'Door traversability', ['Door', 'traversability']),
    ('portal_exit', 'Portal exit', ['Portal exit']),
]
FAMILIES = [('lewm', 'LeWM'), ('pldm', 'PLDM'), ('dinowm', 'DINO-WM')]
SCHEMES = {'original': 'Original', 'scratch': 'Mixed',
           'joint': r'Original $\to$ Mixed (Joint)',
           'frozen': r'Original $\to$ Mixed (Frozen Encoder)'}
COLUMNS = [(f, r) for f, _ in FAMILIES for r in SCHEMES
           if not (f == 'dinowm' and r == 'joint')]
METRICS = [('accuracy', r'Acc. $\uparrow$', 2),
           ('history', r'History win rate $\uparrow$', 2),
           ('nre', r'NRE $\downarrow$', 3)]


def scheme_label(family, regime):
    if family == 'dinowm' and regime == 'frozen':
        return r'Original $\to$ Mixed'
    return SCHEMES[regime].replace('Mixed (Frozen', r'Mixed\newline (Frozen')


def main_table(index):
    def stack(values, alignment='r'):
        return (r'\begin{tabular}[c]{@{}' + alignment + r'@{}}' +
                r' \\ '.join(values) + r'\end{tabular}')

    best = {(task, metric): (min if metric == 'nre' else max)(
                round(c['scores'][metric]['mean'], decimals)
                for (t, _, _), c in index.items() if t == task)
            for task, _, _ in TASKS for metric, _, decimals in METRICS}
    lines = [r'''% Generated by paper/generate_test_tables.py; do not edit values.
\begin{table*}[t]
\centering
\scriptsize
\setlength{\tabcolsep}{2.6pt}
\renewcommand{\arraystretch}{0.95}
\caption{\textbf{Adaptation metrics on the Test split.} Each cell lists Accuracy (\%) $\uparrow$, History win rate (\%) $\uparrow$, and NRE $\downarrow$ from top to bottom. Entries are means; run counts and standard deviations appear in Table~\ref{tab:test-metrics-full}. Speed uses the same scoring rule for Accuracy and History win rate. Bold marks the highest Accuracy and History win rate and lowest NRE per task, including ties at the displayed precision. NRE is measured in each checkpoint's target representation. A dash denotes no comparable checkpoint.}
\label{tab:test-results}
\begin{tabularx}{\textwidth}{@{}ll*{9}{>{\centering\arraybackslash}X}@{}}
\toprule''']
    headings = []
    for _, name, parts in TASKS:
        if len(parts) == 1 and len(name.split()) == 2:
            parts = name.split()
        headings.append(stack(parts, 'c'))
    lines += [' & '.join(['Model', 'Training scheme', *headings]) + r' \\', r'\midrule']
    for fi, (family, model) in enumerate(FAMILIES):
        regimes = [r for f, r in COLUMNS if f == family]
        for ri, regime in enumerate(regimes):
            cells = []
            for task, _, _ in TASKS:
                cell = index.get((task, family, regime))
                if cell is None:
                    cells.append('---')
                    continue
                values = []
                for metric, _, decimals in METRICS:
                    value = cell['scores'][metric]['mean']
                    text = f'{value:.{decimals}f}'
                    if round(value, decimals) == best[task, metric]:
                        text = r'\textbf{' + text + '}'
                    values.append(text)
                cells.append(stack(values))
            if regime in ['joint', 'frozen']:
                training = [r'Original $\to$ Mixed']
                if family != 'dinowm':
                    training.append('(Joint)' if regime == 'joint' else '(Frozen Encoder)')
            else:
                training = [SCHEMES[regime]]
            lines.append(' & '.join([model if ri == 0 else '', stack(training, 'l'), *cells]) + r' \\')
            if ri < len(regimes) - 1:
                lines.append(r'\addlinespace[4pt]')
        if fi < len(FAMILIES) - 1:
            lines.append(r'\midrule')
    lines += [r'\bottomrule', r'\end{tabularx}\end{table*}']
    return '\n'.join(lines) + '\n'


def full_table(index):
    lines = [r'''% Generated by paper/generate_test_tables.py; do not edit values.
\begingroup
\small
\setlength{\tabcolsep}{3pt}
\renewcommand{\arraystretch}{1.05}
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{2.55cm}l>{\raggedright\arraybackslash}p{4.05cm}rrrr@{}}
\caption{\textbf{Complete Test adaptation metrics.} Each row uses the same evaluated checkpoints for all three metrics. Entries are means $\pm$ sample standard deviations across $n$ training runs; a single run has no sample standard deviation. Accuracy and History win rate are percentages; NRE is dimensionless. Speed uses unseen interpolation speeds, and its Accuracy and History win rate use the same scoring rule. Action delay uses seven-frame history. Only available comparable configurations are listed.}\label{tab:test-metrics-full}\label{tab:test-variability}\\
\toprule
Task & Model & Training scheme & $n$ & Accuracy $\uparrow$ & \shortstack{History\\win rate $\uparrow$} & NRE $\downarrow$ \\
\midrule\endfirsthead
\toprule
Task & Model & Training scheme & $n$ & Accuracy $\uparrow$ & \shortstack{History\\win rate $\uparrow$} & NRE $\downarrow$ \\
\midrule\endhead
\bottomrule\endfoot''']
    for task, name, _ in TASKS:
        for family, model in FAMILIES:
            for regime in SCHEMES:
                cell = index.get((task, family, regime))
                if cell is None:
                    continue
                values = []
                for metric, _, decimals in METRICS:
                    stat = cell['scores'][metric]
                    value = f"{stat['mean']:.{decimals}f}"
                    if stat['std'] is not None:
                        value = '$' + value + r'\pm' + f"{stat['std']:.{decimals}f}" + '$'
                    values.append(value)
                lines.append(' & '.join([name, model, scheme_label(family, regime), str(cell['n']), *values]) + r' \\')
        lines.append(r'\addlinespace[3pt]')
    if lines[-1] == r'\addlinespace[3pt]':
        lines.pop()  # Avoid an empty continuation page after the final task.
    lines.append(r'\end{longtable}\endgroup')
    return '\n'.join(lines) + '\n'


def write_tables():
    data = json.loads((ROOT / 'docs/research/data/current_reference_test_v1/metrics.json').read_text())
    assert data['evaluation_split'] == 'test'
    index = {(c['task'], c['family'], c['regime']): c for c in data['cells']}
    assert len(index) == len(data['cells']) == 86
    assert sum(c['n'] for c in index.values()) == 136
    for cell in index.values():
        assert all(cell['scores'][k]['n'] == cell['n'] for k, _, _ in METRICS)
    out = ROOT / 'paper/tables'
    out.mkdir(exist_ok=True)
    (out / 'test_metrics_main.tex').write_text(main_table(index))
    (out / 'test_metrics_full.tex').write_text(full_table(index))
    print('Rendered 86 Test configurations with three metrics in main and appendix tables.')


if __name__ == '__main__':
    write_tables()
